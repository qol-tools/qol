use std::sync::atomic::{AtomicIsize, Ordering};
use std::sync::{Arc, Mutex, MutexGuard};
use std::time::Duration;

use objc2::rc::{autoreleasepool, Retained};
use objc2_app_kit::{
    NSBitmapImageFileType, NSBitmapImageRep, NSPasteboard, NSPasteboardType,
    NSPasteboardTypeFileURL, NSPasteboardTypePNG, NSPasteboardTypeString, NSPasteboardTypeTIFF,
    NSWorkspace,
};
use objc2_foundation::{NSData, NSDictionary, NSString};

use crate::capture::{Capture, CaptureError, Clipboard, Content, Payload, Support, MAX_CLIP_BYTES};

const BACKEND: &str = "nspasteboard";
const CHANGE_POLL: Duration = Duration::from_millis(250);
const CONCEALED: &str = "org.nspasteboard.ConcealedType";
const SKIPPED_MARKERS: [&str; 2] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];

pub(crate) fn open() -> Result<Arc<dyn Clipboard>, CaptureError> {
    Ok(Arc::new(MacClipboard {
        seen: AtomicIsize::new(NSPasteboard::generalPasteboard().changeCount()),
        written: AtomicIsize::new(NO_WRITE),
        secret: Mutex::new(None),
    }))
}

pub(crate) fn probe() -> Support {
    Support::Ready { backend: BACKEND }
}

const NO_WRITE: isize = isize::MIN;

struct MacClipboard {
    seen: AtomicIsize,
    written: AtomicIsize,
    secret: Mutex<Option<Payload>>,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Wanted {
    Files,
    Png,
    Tiff,
    Text,
}

impl Clipboard for MacClipboard {
    fn backend(&self) -> &'static str {
        BACKEND
    }

    fn next_change(&self) -> Result<Capture, CaptureError> {
        loop {
            std::thread::sleep(CHANGE_POLL);
            let capture = autoreleasepool(|_| {
                let pasteboard = NSPasteboard::generalPasteboard();
                let count = pasteboard.changeCount();
                if self.seen.swap(count, Ordering::AcqRel) == count
                    || self.written.load(Ordering::Acquire) == count
                {
                    return None;
                }
                read(&pasteboard)
            });
            if let Some(capture) = capture {
                return Ok(capture);
            }
        }
    }

    fn write(&self, payload: Payload) -> Result<(), CaptureError> {
        autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            pasteboard.clearContents();
            let written = match &payload {
                Payload::Text(text) => pasteboard
                    .setString_forType(&NSString::from_str(text), unsafe {
                        NSPasteboardTypeString
                    }),
                Payload::Secret { text, .. } => {
                    pasteboard.setString_forType(&NSString::from_str(text), unsafe {
                        NSPasteboardTypeString
                    }) && pasteboard
                        .setData_forType(Some(&NSData::new()), &NSString::from_str(CONCEALED))
                }
                Payload::Png(png) => pasteboard
                    .setData_forType(Some(&NSData::with_bytes(png)), unsafe {
                        NSPasteboardTypePNG
                    }),
            };
            self.written
                .store(pasteboard.changeCount(), Ordering::Release);
            if !written {
                return Err(CaptureError::Failed(
                    "The clipboard did not take this clip. Try copying again.".to_string(),
                ));
            }
            *lock(&self.secret) = matches!(payload, Payload::Secret { .. }).then_some(payload);
            Ok(())
        })
    }

    fn clear_expired_secret(&self) -> Result<(), CaptureError> {
        {
            let mut secret = lock(&self.secret);
            if !secret.as_ref().is_some_and(Payload::is_expired_secret) {
                return Ok(());
            }
            *secret = None;
        }
        autoreleasepool(|_| {
            let pasteboard = NSPasteboard::generalPasteboard();
            if pasteboard.changeCount() == self.written.load(Ordering::Acquire) {
                pasteboard.clearContents();
                self.written
                    .store(pasteboard.changeCount(), Ordering::Release);
            }
        });
        Ok(())
    }
}

fn read(pasteboard: &NSPasteboard) -> Option<Capture> {
    let types: Vec<String> = pasteboard
        .types()?
        .iter()
        .map(|kind| kind.to_string())
        .collect();
    if types
        .iter()
        .any(|kind| SKIPPED_MARKERS.contains(&kind.as_str()))
    {
        log::debug!("clipboard change marked transient; skipped");
        return None;
    }
    let content = match choose(&types)? {
        Wanted::Files => Content::Files(file_paths(pasteboard)?),
        Wanted::Png => Content::Png(bytes(pasteboard, unsafe { NSPasteboardTypePNG })?),
        Wanted::Tiff => {
            let tiff = pasteboard.dataForType(unsafe { NSPasteboardTypeTIFF })?;
            Content::Png(tiff_as_png(&tiff)?)
        }
        Wanted::Text => Content::Text(
            pasteboard
                .stringForType(unsafe { NSPasteboardTypeString })?
                .to_string(),
        ),
    };
    Some(Capture {
        content,
        app: frontmost_app(),
        sensitive: crate::secrets::flagged_by_source(&types),
    })
}

fn choose(types: &[String]) -> Option<Wanted> {
    let offered =
        |kind: &NSPasteboardType| types.iter().any(|offered| kind.to_string() == *offered);
    unsafe {
        [
            (NSPasteboardTypeFileURL, Wanted::Files),
            (NSPasteboardTypePNG, Wanted::Png),
            (NSPasteboardTypeTIFF, Wanted::Tiff),
            (NSPasteboardTypeString, Wanted::Text),
        ]
    }
    .into_iter()
    .find_map(|(kind, wanted)| offered(kind).then_some(wanted))
}

fn file_paths(pasteboard: &NSPasteboard) -> Option<Vec<String>> {
    let urls: String = pasteboard
        .pasteboardItems()?
        .iter()
        .filter_map(|item| item.stringForType(unsafe { NSPasteboardTypeFileURL }))
        .map(|url| format!("{url}\n"))
        .collect();
    let paths = crate::capture::uri::parse_uri_list(&urls);
    (!paths.is_empty()).then_some(paths)
}

fn bytes(pasteboard: &NSPasteboard, kind: &NSPasteboardType) -> Option<Vec<u8>> {
    let data = pasteboard.dataForType(kind)?;
    within_cap(&data).then(|| data.to_vec())
}

fn tiff_as_png(tiff: &NSData) -> Option<Vec<u8>> {
    if !within_cap(tiff) {
        return None;
    }
    let image = NSBitmapImageRep::imageRepWithData(tiff)?;
    let png: Retained<NSData> = unsafe {
        image.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new())
    }?;
    within_cap(&png).then(|| png.to_vec())
}

fn within_cap(data: &NSData) -> bool {
    let fits = data.len() <= MAX_CLIP_BYTES;
    if !fits {
        log::debug!("clipboard item exceeds {MAX_CLIP_BYTES} bytes; skipped");
    }
    fits
}

fn frontmost_app() -> Option<String> {
    let app = NSWorkspace::sharedWorkspace().frontmostApplication()?;
    Some(app.localizedName()?.to_string())
}

fn lock<T>(mutex: &Mutex<T>) -> MutexGuard<'_, T> {
    mutex
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner())
}

#[cfg(test)]
mod tests {
    use super::{choose, Wanted};

    #[test]
    fn choice_prefers_files_then_png_then_tiff_then_text() {
        let cases: &[(&[&str], Option<Wanted>)] = &[
            (
                &["public.file-url", "public.tiff", "public.utf8-plain-text"],
                Some(Wanted::Files),
            ),
            (&["public.tiff", "public.png"], Some(Wanted::Png)),
            (
                &["public.utf8-plain-text", "public.tiff"],
                Some(Wanted::Tiff),
            ),
            (
                &["public.html", "public.utf8-plain-text"],
                Some(Wanted::Text),
            ),
            (&["com.apple.flat-rtfd"], None),
        ];
        for (types, wanted) in cases {
            let types: Vec<String> = types.iter().map(|kind| (*kind).to_string()).collect();
            assert_eq!(choose(&types), *wanted, "types: {types:?}");
        }
    }
}
