pub fn alt_tab_cinnamon_js() -> String {
    let palette = alt_tab_preview_plane_dark();
    let mut out = String::from("/* @generated by qol-theme-css; do not edit by hand. */\n");
    out.push_str("module.exports = {\n");
    push_js(&mut out, "backdrop", &clutter_rgba(palette.backdrop_rgba));
    push_js(&mut out, "labelText", &hex6(palette.label_text));
    push_js(&mut out, "cardBg", &clutter_rgba(palette.card_bg_rgba));
    push_js(
        &mut out,
        "cardBorder",
        &clutter_rgba(palette.card_border_rgba),
    );
    push_js(
        &mut out,
        "cardSelectedBg",
        &clutter_rgba(palette.card_selected_bg_rgba),
    );
    push_js(
        &mut out,
        "cardSelectedBorder",
        &clutter_rgba(palette.card_selected_border_rgba),
    );
    out.push_str("};\n");
    out
}

pub fn tray_theme_js() -> String {
    let default = dark_accent_preset(PROD_ACCENT_KEY).expect("default accent exists");
    let mut out = String::from("/* @generated by qol-theme-css; do not edit by hand. */\n");
    out.push_str("export const QOL_ACCENT_PRESETS = [\n");
    for preset in dark_accent_presets() {
        let _ = writeln!(
            out,
            "    {{ key: \"{}\", label: \"{}\", rgb: \"{}\", hover: \"{}\" }},",
            preset.key,
            preset.label,
            rgb_string(preset.rgb),
            hex6(preset.hover)
        );
    }
    out.push_str("];\n");
    let _ = writeln!(
        out,
        "export const QOL_DEFAULT_ACCENT = \"{PROD_ACCENT_KEY}\";"
    );
    let _ = writeln!(out, "export const QOL_DEV_ACCENT = \"{DEV_ACCENT_KEY}\";");
    let _ = writeln!(
        out,
        "export const QOL_DEFAULT_ACCENT_RGB = \"{}\";",
        rgb_string(default.rgb)
    );
    out
}

