fn push_accent_preset_variables(out: &mut String) {
    for preset in dark_accent_presets() {
        push_rgb(out, &format!("qol-accent-{}-rgb", preset.key), preset.rgb);
        push_hex(
            out,
            &format!("qol-accent-{}-hover", preset.key),
            preset.hover,
        );
    }
}

