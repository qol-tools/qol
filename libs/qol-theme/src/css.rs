fn plugin_profile_css(component_variables: fn(&str, Theme) -> String) -> String {
    let mut out = plugin_profile_base_css(dark_theme(), component_variables);
    let overrides = accent_override_blocks(&out, component_variables);
    out.push_str(&overrides);
    out
}

fn plugin_profile_base_css(theme: Theme, component_variables: fn(&str, Theme) -> String) -> String {
    let mut out = String::from("/* @generated by qol-theme-css; do not edit by hand. */\n");
    out.push_str(&css_variables(":root", theme));
    out.push_str(&component_variables(":root", theme));
    out
}

fn accent_override_blocks(base: &str, component_variables: fn(&str, Theme) -> String) -> String {
    let base_variables = css_variable_map(base);
    let mut out = String::new();

    for preset in dark_accent_presets() {
        let variant =
            plugin_profile_base_css(dark_theme_with_accent_key(preset.key), component_variables);
        let diff = css_variable_diff(&base_variables, &variant);
        if diff.is_empty() {
            continue;
        }
        let _ = writeln!(out, ":root[data-qol-accent=\"{}\"] {{", preset.key);
        for (name, value) in diff {
            let _ = writeln!(out, "    {name}: {value};");
        }
        out.push_str("}\n");
    }

    out
}

fn css_variable_diff(
    base_variables: &HashMap<String, String>,
    variant_css: &str,
) -> Vec<(String, String)> {
    css_variable_entries(variant_css)
        .into_iter()
        .filter(|(name, value)| base_variables.get(name) != Some(value))
        .collect()
}

fn css_variable_map(css: &str) -> HashMap<String, String> {
    css_variable_entries(css).into_iter().collect()
}

fn css_variable_entries(css: &str) -> Vec<(String, String)> {
    css.lines().filter_map(css_variable_entry).collect()
}

fn css_variable_entry(line: &str) -> Option<(String, String)> {
    let line = line.trim();
    if !line.starts_with("--") {
        return None;
    }
    let (name, value) = line.split_once(':')?;
    Some((
        name.to_string(),
        value.trim().trim_end_matches(';').to_string(),
    ))
}

