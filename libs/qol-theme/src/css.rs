fn push_hex(out: &mut String, name: &str, color: u32) {
    let _ = writeln!(out, "    --{name}: #{:06x};", color & 0x00ff_ffff);
}

fn push_rgb(out: &mut String, name: &str, color: u32) {
    let (red, green, blue) = rgb_channels(color);
    let _ = writeln!(out, "    --{name}: {red}, {green}, {blue};");
}

fn push_value(out: &mut String, name: &str, value: &str) {
    let _ = writeln!(out, "    --{name}: {value};");
}

fn push_js(out: &mut String, name: &str, value: &str) {
    let _ = writeln!(out, "    {name}: \"{value}\",");
}

fn clutter_rgba(color: u32) -> String {
    let red = (color >> 24) & 0xff;
    let green = (color >> 16) & 0xff;
    let blue = (color >> 8) & 0xff;
    let alpha = color & 0xff;
    format!("rgba({red}, {green}, {blue}, {alpha})")
}

fn hex6(color: u32) -> String {
    format!("#{:06x}", color & 0x00ff_ffff)
}

fn rgb_string(color: u32) -> String {
    let (red, green, blue) = rgb_channels(color);
    format!("{red}, {green}, {blue}")
}

fn rgb_channels(color: u32) -> (u32, u32, u32) {
    ((color >> 16) & 0xff, (color >> 8) & 0xff, color & 0xff)
}
