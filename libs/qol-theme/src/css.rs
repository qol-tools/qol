pub fn tray_theme_js() -> String {
    let default = dark_accent_preset(PROD_ACCENT_KEY).expect("default accent exists");
    let tray = DARK_TRAY_INTERNAL;
    let mut out = String::from("/* @generated by qol-theme-css; do not edit by hand. */\n");
    out.push_str("export const QOL_ACCENT_PRESETS = [\n");
    for preset in dark_accent_presets() {
        let _ = writeln!(
            out,
            "    {{ key: \"{}\", label: \"{}\", rgb: \"{}\", hover: \"{}\" }},",
            preset.key,
            preset.label,
            rgb_string(preset.rgb),
            hex6(preset.hover)
        );
    }
    out.push_str("];\n");
    let _ = writeln!(
        out,
        "export const QOL_DEFAULT_ACCENT = \"{PROD_ACCENT_KEY}\";"
    );
    let _ = writeln!(out, "export const QOL_DEV_ACCENT = \"{DEV_ACCENT_KEY}\";");
    let _ = writeln!(
        out,
        "export const QOL_DEFAULT_ACCENT_RGB = \"{}\";",
        rgb_string(default.rgb)
    );
    out.push_str("export const QOL_TRAY_INTERNAL_COLORS = {\n");
    push_js(&mut out, "dissolveTargetColor", &hex6(tray.dissolve_target));
    push_js(&mut out, "transparentKeyword", "transparent");
    push_js(
        &mut out,
        "transparentRgba",
        &css_rgba_milli(tray.transparent_rgba),
    );
    push_js(
        &mut out,
        "minimapInactiveFill",
        &css_rgba_milli(tray.minimap_inactive_fill),
    );
    push_js(
        &mut out,
        "minimapInactiveStroke",
        &css_rgba_milli(tray.minimap_inactive_stroke),
    );
    push_js(
        &mut out,
        "minimapInactiveText",
        &css_rgba_milli(tray.minimap_inactive_text),
    );
    push_js(
        &mut out,
        "minimapActiveFill",
        &css_rgba_milli(tray.minimap_active_fill),
    );
    push_js(
        &mut out,
        "minimapActiveStroke",
        &css_rgba_milli(tray.minimap_active_stroke),
    );
    push_js(
        &mut out,
        "minimapActiveText",
        &css_rgba_milli(tray.minimap_active_text),
    );
    push_js(&mut out, "configQrDark", &hex6(tray.config_qr_dark));
    push_js(&mut out, "configQrLight", &hex6(tray.config_qr_light));
    push_js(
        &mut out,
        "configLiveColorFallback",
        &hex6(tray.config_live_color_fallback),
    );
    push_js(
        &mut out,
        "configColorThumbStroke",
        &hex6(tray.config_color_thumb_stroke),
    );
    push_js(
        &mut out,
        "configColorThumbShadow",
        &css_rgba_milli(tray.config_color_thumb_shadow),
    );
    out.push_str("};\n");
    out
}

