use std::fmt::Write;

use crate::{dark_theme, Theme};

pub fn dark_css() -> String {
    let mut out = String::from("/* @generated by qol-theme-css; do not edit by hand. */\n");
    out.push_str(&css_variables(":root", dark_theme()));
    out
}

pub fn alt_tab_cinnamon_js() -> String {
    let palette = crate::theme_for_native_key(None, None)
        .components
        .alt_tab_preview_plane;
    let mut out = String::from("/* @generated by qol-theme-css; do not edit by hand. */\n");
    out.push_str("module.exports = {\n");
    push_js(&mut out, "backdrop", &clutter_rgba(palette.backdrop_rgba));
    push_js(&mut out, "labelText", &hex_string(palette.label_text));
    push_js(&mut out, "cardBg", &clutter_rgba(palette.card_bg_rgba));
    push_js(
        &mut out,
        "cardBorder",
        &clutter_rgba(palette.card_border_rgba),
    );
    push_js(
        &mut out,
        "cardSelectedBg",
        &clutter_rgba(palette.card_selected_bg_rgba),
    );
    push_js(
        &mut out,
        "cardSelectedBorder",
        &clutter_rgba(palette.card_selected_border_rgba),
    );
    out.push_str("};\n");
    out
}

pub fn css_variables(selector: &str, theme: Theme) -> String {
    let palette = theme.system;
    let reference = theme.reference;
    let mut out = String::new();
    let _ = writeln!(out, "{selector} {{");
    push_rgb(&mut out, "qol-system-accent-rgb", palette.accent);
    push_rgb(&mut out, "qol-system-success-rgb", palette.success);
    push_rgb(&mut out, "qol-system-danger-rgb", palette.danger);
    push_rgb(&mut out, "qol-system-warning-rgb", palette.warning);
    push_rgb(&mut out, "qol-system-ink-rgb", reference.black);
    push_rgb(&mut out, "qol-system-paper-rgb", reference.white);
    push_hex(
        &mut out,
        "qol-system-surface-canvas",
        palette.surface_canvas,
    );
    push_hex(
        &mut out,
        "qol-system-surface-elevated",
        palette.surface_elevated,
    );
    push_hex(
        &mut out,
        "qol-system-surface-raised",
        palette.surface_raised,
    );
    push_hex(
        &mut out,
        "qol-system-surface-hovered",
        palette.surface_hovered,
    );
    push_hex(&mut out, "qol-system-text-primary", palette.text_primary);
    push_hex(
        &mut out,
        "qol-system-text-secondary",
        palette.text_secondary,
    );
    push_hex(&mut out, "qol-system-text-muted", palette.text_muted);
    push_hex(&mut out, "qol-system-text-faint", palette.text_faint);
    push_hex(&mut out, "qol-system-border-subtle", palette.border_subtle);
    out.push_str("}\n");
    out
}

fn push_hex(out: &mut String, name: &str, color: u32) {
    let _ = writeln!(out, "    --{name}: #{:06x};", color & 0x00ff_ffff);
}

fn push_rgb(out: &mut String, name: &str, color: u32) {
    let (red, green, blue) = rgb_channels(color);
    let _ = writeln!(out, "    --{name}: {red}, {green}, {blue};");
}

fn push_js(out: &mut String, name: &str, value: &str) {
    let _ = writeln!(out, "    {name}: \"{value}\",");
}

fn clutter_rgba(color: u32) -> String {
    let red = (color >> 24) & 0xff;
    let green = (color >> 16) & 0xff;
    let blue = (color >> 8) & 0xff;
    let alpha = color & 0xff;
    format!("rgba({red}, {green}, {blue}, {alpha})")
}

pub fn hex_string(color: u32) -> String {
    format!("#{:06x}", color & 0x00ff_ffff)
}

pub fn rgb_string(color: u32) -> String {
    let (red, green, blue) = rgb_channels(color);
    format!("{red}, {green}, {blue}")
}

fn rgb_channels(color: u32) -> (u32, u32, u32) {
    ((color >> 16) & 0xff, (color >> 8) & 0xff, color & 0xff)
}
